"use strict";

/*
 * Obtain references to the HTML elements used by the application.
 *
 * These IDs correspond to elements defined in index.html.
 */
const searchInput = document.getElementById("searchInput");
const typeFilter = document.getElementById("typeFilter");
const paintGrid = document.getElementById("paintGrid");
const resultCount = document.getElementById("resultCount");

/*
 * Store all paint records returned by the API.
 *
 * Keeping the original dataset in memory allows the frontend
 * to filter results without making a new API request
 * whenever the user types or changes the dropdown.
 */
let allPaints = [];

/**
 * Retrieve paint records from the ASP.NET Core REST API.
 *
 * Sends an HTTP GET request to /api/paints using Fetch.
 * Converts the JSON response into JavaScript objects.
 *
 * On success:
 * - Store the paint records.
 * - Populate the paint type dropdown.
 * - Display the catalog.
 *
 * On failure:
 * - Log the error for debugging.
 * - Display a user-friendly error message.
 *
 * @returns {Promise<void>}
 */
async function loadPaints() {
    try {
        const response = await fetch("/api/paints");

        if (!response.ok) {
            throw new Error("Unable to retrieve paints.");
        }

        allPaints = await response.json();

        populateTypeFilter();
        displayPaints();
    } catch (error) {
        console.error("API error:", error);

        resultCount.textContent = "Unable to load paints.";
        paintGrid.replaceChildren();

        const message = document.createElement("p");
        message.className = "empty-message";
        message.textContent = "Please check that the API is running.";
        paintGrid.appendChild(message);
    }
}

/**
 * Populate the paint type dropdown using API data.
 *
 * The Set object removes duplicate paint types.
 * Sorting places the options in alphabetical order.
 *
 * Each option is created using DOM methods rather
 * than inserting HTML strings.
 *
 * @returns {void}
 */
function populateTypeFilter() {
    const types = [...new Set(
        allPaints
            .map(paint => paint.type)
            .filter(Boolean)
    )].sort();

    for (const type of types) {
        const option = document.createElement("option");
        option.value = type;
        option.textContent = type;
        typeFilter.appendChild(option);
    }
}

/**
 * Validate a paint's hexadecimal color value.
 *
 * Accepts three-digit or six-digit hexadecimal colors,
 * with or without a leading # symbol.
 *
 * Invalid or missing values use a neutral gray fallback.
 *
 * @param {unknown} value - Color value from the API.
 * @returns {string} Valid CSS hexadecimal color.
 */
function getPaintColor(value) {
    if (typeof value !== "string") {
        return "#dddddd";
    }

    const color = value.trim();

    if (/^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i.test(color)) {
        return color;
    }

    if (/^(?:[0-9a-f]{3}|[0-9a-f]{6})$/i.test(color)) {
        return "#" + color;
    }

    return "#dddddd";
}

/**
 * Filter and display paint records.
 *
 * Reads two user inputs:
 * 1. Search text entered by the user.
 * 2. Selected paint type.
 *
 * Both conditions must match for a paint to appear.
 *
 * The results are updated without reloading the page
 * or requesting additional data from the backend.
 *
 * @returns {void}
 */
function displayPaints() {
    // Normalize search text for case-insensitive matching.
    const search = searchInput.value.trim().toLowerCase();
    const selectedType = typeFilter.value;

    // Apply both filters to the original paint collection.
    const filteredPaints = allPaints.filter(paint => {
        const matchesName = (paint.name ?? "")
            .toLowerCase()
            .includes(search);

        const matchesType =
            selectedType === "" || paint.type === selectedType;

        return matchesName && matchesType;
    });

    // Update the accessible result counter.
    resultCount.textContent =
        `Showing ${filteredPaints.length} of ${allPaints.length} paints`;

    // Remove previously displayed paint cards.
    paintGrid.replaceChildren();

    // Explain when no records match the selected filters.
    if (filteredPaints.length === 0) {
        const message = document.createElement("p");
        message.className = "empty-message";
        message.textContent = "No paints match your search.";
        paintGrid.appendChild(message);
        return;
    }

    // Create a new card for every matching paint.
    for (const paint of filteredPaints) {
        paintGrid.appendChild(createPaintCard(paint));
    }
}

/**
 * Create an HTML card representing one paint record.
 *
 * Displays:
 * - Paint color swatch.
 * - Paint name.
 * - Paint type.
 * - Hexadecimal color code.
 * - Optional external product link.
 *
 * DOM methods and textContent are used to avoid
 * interpreting paint data as executable HTML.
 *
 * @param {object} paint - Paint record returned by the API.
 * @returns {HTMLElement} Completed paint card.
 */
function createPaintCard(paint) {
    const card = document.createElement("article");
    card.className = "paint-card";

    // Create a visual preview of the paint color.
    const swatch = document.createElement("div");
    swatch.className = "paint-swatch";
    swatch.style.backgroundColor = getPaintColor(paint.value);

    // Hide the decorative swatch from screen readers.
    // The color code is also provided as text.
    swatch.setAttribute("aria-hidden", "true");

    // Container for the paint's descriptive information.
    const details = document.createElement("div");
    details.className = "paint-details";

    const name = document.createElement("h2");
    name.textContent = paint.name;

    const type = document.createElement("p");
    type.className = "paint-type";
    type.textContent = paint.type || "Unknown type";

    const code = document.createElement("span");
    code.className = "paint-code";
    code.textContent = paint.value || "No color code";

    details.append(name, type, code);

    /*
     * Add an external product link only when the URL is valid.
     *
     * HTTPS is required to avoid insecure product links.
     * noopener prevents the new tab from accessing this window.
     * noreferrer prevents sending referrer information.
     */
    if (paint.url) {
        try {
            const url = new URL(paint.url);

            if (url.protocol === "https:") {
                const link = document.createElement("a");
                link.className = "paint-link";
                link.href = url.href;
                link.target = "_blank";
                link.rel = "noopener noreferrer";
                link.textContent = "View Paint";

                details.appendChild(document.createElement("br"));
                details.appendChild(link);
            }
        } catch {
            // Ignore invalid URLs imported from the workbook.
        }
    }

    card.append(swatch, details);
    return card;
}

/*
 * Register event listeners for the two user inputs.
 *
 * The input event updates results while the user types.
 * The change event updates results when a paint type
 * is selected from the dropdown.
 */
searchInput.addEventListener("input", displayPaints);
typeFilter.addEventListener("change", displayPaints);

/*
 * Start the application by retrieving paint records.
 * The deferred script runs after HTML parsing completes.
 */
loadPaints();
